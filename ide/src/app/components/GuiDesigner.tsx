'use client';

import React, { useCallback, useEffect, useState } from 'react';

export interface Widget {
  id: string;
  kind: 'label' | 'button' | 'input' | 'checkbox' | 'select' | 'textarea' | 'image';
  text: string;
  x: number;
  y: number;
  w: number;
  h: number;
  name: string;
}

const WIDGET_DEFAULTS: Record<Widget['kind'], Omit<Widget, 'id' | 'x' | 'y' | 'name'>> = {
  label: { kind: 'label', text: 'Label', w: 100, h: 20 },
  button: { kind: 'button', text: 'Button', w: 80, h: 28 },
  input: { kind: 'input', text: '', w: 160, h: 28 },
  checkbox: { kind: 'checkbox', text: 'Check me', w: 120, h: 20 },
  select: { kind: 'select', text: 'Option 1', w: 140, h: 28 },
  textarea: { kind: 'textarea', text: '', w: 200, h: 80 },
  image: { kind: 'image', text: 'image.png', w: 64, h: 64 },
};

let counter = 0;
const uid = () => `w${++counter}`;

export function generateRakCode(title: string, width: number, height: number, widgets: Widget[]): string {
  const lines: string[] = [];
  lines.push('// Generated by the Rak GUI Designer. Edit freely.');
  lines.push('');
  lines.push('fn on_widget(msg) { return msg }');
  lines.push('');
  lines.push(`let html = r#"<div style='position:relative;width:${width}px;height:${height}px;font-family:monospace'>"`);
  for (const w of widgets) {
    const style = `position:absolute;left:${w.x}px;top:${w.y}px;width:${w.w}px;height:${w.h}px`;
    switch (w.kind) {
      case 'label':
        lines.push(`  + "<div style='${style}'>${escapeHtml(w.text)}</div>"`);
        break;
      case 'button':
        lines.push(`  + "<button style='${style}' onclick=\\"rak_call('on_widget','${escapeAttr(w.name)}')\\">${escapeHtml(w.text)}</button>"`);
        break;
      case 'input':
        lines.push(`  + "<input style='${style}' placeholder='${escapeAttr(w.text)}' />"`);
        break;
      case 'checkbox':
        lines.push(`  + "<label style='${style}'><input type='checkbox' /> ${escapeHtml(w.text)}</label>"`);
        break;
      case 'select':
        lines.push(`  + "<select style='${style}'><option>${escapeHtml(w.text)}</option></select>"`);
        break;
      case 'textarea':
        lines.push(`  + "<textarea style='${style}' placeholder='${escapeAttr(w.text)}'></textarea>"`);
        break;
      case 'image':
        lines.push(`  + "<img style='${style}' src='${escapeAttr(w.text)}' alt='' />"`);
        break;
    }
  }
  lines.push('  + "</div>"#');
  lines.push('');
  lines.push('gui_callback("on_widget", on_widget)');
  lines.push(`let win = gui_open("${escapeAttr(title)}", html, ${width}, ${height})`);
  lines.push('gui_wait()');
  return lines.join('\n');
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
function escapeAttr(s: string): string {
  return s.replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

interface Props {
  onGenerate: (code: string) => void;
  onClose: () => void;
}

export default function GuiDesigner({ onGenerate, onClose }: Props) {
  const [title, setTitle] = useState('Rak GUI');
  const [width, setWidth] = useState(480);
  const [height, setHeight] = useState(320);
  const [widgets, setWidgets] = useState<Widget[]>([]);
  const [selected, setSelected] = useState<string | null>(null);
  const [dragging, setDragging] = useState<{ id: string; dx: number; dy: number } | null>(null);

  const addWidget = (kind: Widget['kind']) => {
    const d = WIDGET_DEFAULTS[kind];
    const w: Widget = { id: uid(), name: `${kind}_${widgets.length + 1}`, x: 20, y: 20, ...d };
    setWidgets(prev => [...prev, w]);
    setSelected(w.id);
  };

  const updateWidget = (id: string, patch: Partial<Widget>) => {
    setWidgets(prev => prev.map(w => (w.id === id ? { ...w, ...patch } : w)));
  };
  const removeWidget = (id: string) => {
    setWidgets(prev => prev.filter(w => w.id !== id));
    if (selected === id) setSelected(null);
  };

  const onMouseDown = (e: React.MouseEvent, w: Widget) => {
    e.preventDefault();
    setSelected(w.id);
    setDragging({ id: w.id, dx: e.clientX - w.x, dy: e.clientY - w.y });
  };
  const onMouseMove = useCallback((e: MouseEvent) => {
    if (!dragging) return;
    updateWidget(dragging.id, { x: Math.max(0, e.clientX - dragging.dx), y: Math.max(0, e.clientY - dragging.dy) });
  }, [dragging]);
  const onMouseUp = useCallback(() => setDragging(null), []);

  useEffect(() => {
    window.addEventListener('mousemove', onMouseMove);
    window.addEventListener('mouseup', onMouseUp);
    return () => { window.removeEventListener('mousemove', onMouseMove); window.removeEventListener('mouseup', onMouseUp); };
  }, [onMouseMove, onMouseUp]);

  const sel = widgets.find(w => w.id === selected) || null;

  const handleGenerate = () => {
    onGenerate(generateRakCode(title, width, height, widgets));
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70">
      <div className="bg-zinc-900 border border-zinc-700 rounded-lg w-[960px] h-[640px] flex flex-col overflow-hidden">
        <div className="flex items-center justify-between px-4 py-2 border-b border-zinc-800">
          <h2 className="text-sm font-semibold text-emerald-400">Rak GUI Designer</h2>
          <div className="flex gap-2">
            <button onClick={handleGenerate} className="px-3 py-1 bg-emerald-600 hover:bg-emerald-500 text-white text-xs rounded">Generate Rak code</button>
            <button onClick={onClose} className="px-3 py-1 bg-zinc-800 hover:bg-zinc-700 text-zinc-300 text-xs rounded">Close</button>
          </div>
        </div>

        <div className="flex flex-1 overflow-hidden">
          {/* Palette */}
          <div className="w-40 border-r border-zinc-800 p-2 space-y-1 overflow-y-auto">
            <div className="text-[10px] text-zinc-500 uppercase mb-1">Widgets</div>
            {(Object.keys(WIDGET_DEFAULTS) as Widget['kind'][]).map(k => (
              <button key={k} onClick={() => addWidget(k)} className="w-full text-left px-2 py-1 text-xs text-zinc-300 hover:bg-zinc-800 rounded capitalize">{k}</button>
            ))}
            <div className="text-[10px] text-zinc-500 uppercase mt-3 mb-1">Canvas</div>
            <label className="block text-[10px] text-zinc-400">Title
              <input value={title} onChange={e => setTitle(e.target.value)} className="w-full mt-0.5 px-1 py-0.5 bg-zinc-800 border border-zinc-700 rounded text-xs" />
            </label>
            <label className="block text-[10px] text-zinc-400 mt-1">Width
              <input type="number" value={width} onChange={e => setWidth(+e.target.value)} className="w-full mt-0.5 px-1 py-0.5 bg-zinc-800 border border-zinc-700 rounded text-xs" />
            </label>
            <label className="block text-[10px] text-zinc-400 mt-1">Height
              <input type="number" value={height} onChange={e => setHeight(+e.target.value)} className="w-full mt-0.5 px-1 py-0.5 bg-zinc-800 border border-zinc-700 rounded text-xs" />
            </label>
          </div>

          {/* Canvas */}
          <div className="flex-1 bg-zinc-950 p-4 overflow-auto">
            <div
              className="relative bg-white rounded shadow-lg"
              style={{ width, height }}
            >
              {widgets.map(w => (
                <div
                  key={w.id}
                  onMouseDown={e => onMouseDown(e, w)}
                  style={{ position: 'absolute', left: w.x, top: w.y, width: w.w, height: w.h, cursor: 'move' }}
                  className={`border ${selected === w.id ? 'border-emerald-500' : 'border-zinc-400'} bg-zinc-100 text-zinc-900 text-xs flex items-center justify-center overflow-hidden`}
                >
                  {w.text || w.kind}
                </div>
              ))}
            </div>
          </div>

          {/* Properties */}
          <div className="w-56 border-l border-zinc-800 p-2 space-y-2 overflow-y-auto">
            <div className="text-[10px] text-zinc-500 uppercase">Properties</div>
            {sel ? (
              <>
                <label className="block text-[10px] text-zinc-400">Kind
                  <input value={sel.kind} disabled className="w-full mt-0.5 px-1 py-0.5 bg-zinc-800 border border-zinc-700 rounded text-xs text-zinc-500" />
                </label>
                <label className="block text-[10px] text-zinc-400">Name
                  <input value={sel.name} onChange={e => updateWidget(sel.id, { name: e.target.value })} className="w-full mt-0.5 px-1 py-0.5 bg-zinc-800 border border-zinc-700 rounded text-xs" />
                </label>
                <label className="block text-[10px] text-zinc-400">Text
                  <input value={sel.text} onChange={e => updateWidget(sel.id, { text: e.target.value })} className="w-full mt-0.5 px-1 py-0.5 bg-zinc-800 border border-zinc-700 rounded text-xs" />
                </label>
                <div className="grid grid-cols-2 gap-1">
                  {(['x', 'y', 'w', 'h'] as const).map(k => (
                    <label key={k} className="block text-[10px] text-zinc-400">{k.toUpperCase()}
                      <input type="number" value={sel[k]} onChange={e => updateWidget(sel.id, { [k]: +e.target.value })} className="w-full mt-0.5 px-1 py-0.5 bg-zinc-800 border border-zinc-700 rounded text-xs" />
                    </label>
                  ))}
                </div>
                <button onClick={() => removeWidget(sel.id)} className="w-full mt-2 px-2 py-1 bg-red-600/20 hover:bg-red-600/40 text-red-400 text-xs rounded">Delete</button>
              </>
            ) : (
              <div className="text-xs text-zinc-600 italic">Select a widget</div>
            )}
            <div className="text-[10px] text-zinc-600 mt-4">
              {widgets.length} widget{widgets.length !== 1 ? 's' : ''}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
